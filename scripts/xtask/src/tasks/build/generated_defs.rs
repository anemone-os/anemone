//! Rendering for generated kernel configuration, Platform, and boot inputs.

use std::path::Path;

use anyhow::Context;
use xshell::Shell;

use crate::{config::system_target::StaticIpv4, log_progress};

use super::{BuildContext, device_tree};

impl BuildContext {
    pub(super) fn gen_rust_defs(&self) -> anyhow::Result<()> {
        let kconfig_defs = self.resolved.kernel_config.parameters.gen_kconfig_defs();
        let platform_defs = self
            .resolved
            .platform
            .gen_platform_defs(&self.resolved.target.root);
        let boot_defs = self.gen_boot_defs()?;
        let network_defs = render_network_defs(
            self.resolved
                .target
                .network
                .as_ref()
                .map(|value| &value.ipv4),
        );
        let platform_dtb_defs = device_tree::render_kernel_defs(&self.resolved.platform)?;
        let platform_defs = format!("{platform_defs}\n{platform_dtb_defs}");
        // write to both loader and kernel src directories
        let kconfig_defs_path = format!("anemone-kernel/src/kconfig_defs.rs",);
        let platform_defs_path = format!("anemone-kernel/src/platform_defs.rs",);
        let boot_defs_path = "anemone-kernel/src/boot_defs.rs";
        let network_defs_path = "anemone-kernel/src/network_defs.rs";
        log_progress!(
            "GENDEFS",
            "Generating kconfig_defs.rs, platform_defs.rs, boot_defs.rs, and network_defs.rs"
        );
        let sh = Shell::new()?;
        sh.write_file(&kconfig_defs_path, &kconfig_defs)?;
        sh.write_file(&platform_defs_path, &platform_defs)?;
        sh.write_file(boot_defs_path, &boot_defs)?;
        sh.write_file(network_defs_path, &network_defs)?;
        Ok(())
    }
}

pub(super) fn render_network_defs(ipv4: Option<&StaticIpv4>) -> String {
    let deployment = ipv4
        .map(|ipv4| {
            let interface = format!("{:?}", ipv4.interface);
            let address = render_ipv4(ipv4.address.octets());
            let gateway = ipv4
                .default_gateway
                .map(|gateway| format!("Some({})", render_ipv4(gateway.octets())))
                .unwrap_or_else(|| "None".to_string());
            format!(
                "pub(crate) const STATIC_IPV4_DEPLOYMENT: Option<StaticIpv4Deployment> =\n    Some(StaticIpv4Deployment {{\n        interface: {interface},\n        address: {address},\n        prefix: {},\n        default_gateway: {gateway},\n    }});",
                ipv4.prefix
            )
        })
        .unwrap_or_else(|| {
            "pub(crate) const STATIC_IPV4_DEPLOYMENT: Option<StaticIpv4Deployment> = None;"
                .to_string()
        });

    format!(
        r#"// @generated by `xtask build`; do not edit.
#[derive(Clone, Copy, Debug)]
pub(crate) struct StaticIpv4Deployment {{
    pub(crate) interface: &'static str,
    pub(crate) address: [u8; 4],
    pub(crate) prefix: u8,
    pub(crate) default_gateway: Option<[u8; 4]>,
}}

{deployment}
"#
    )
}

fn render_ipv4(octets: [u8; 4]) -> String {
    format!(
        "[{}, {}, {}, {}]",
        octets[0], octets[1], octets[2], octets[3]
    )
}

pub(super) fn render_rootfs_entry_boot_defs(argv: Option<&[String]>) -> String {
    render_boot_defs(&format!(
        "InitialProgramSource::RootfsEntry {{ argv: {} }}",
        render_argv(argv)
    ))
}

pub(super) fn render_embedded_app_boot_defs(
    path: &Path,
    argv: Option<&[String]>,
) -> anyhow::Result<String> {
    let path = path
        .to_str()
        .context("embedded app export path must be valid UTF-8")?;
    let path_literal = format!("{path:?}");
    let initial_program = format!(
        r#"InitialProgramSource::EmbeddedApp {{
    bytes: include_bytes!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../",
        {path_literal}
    )),
    argv: {},
}}"#,
        render_argv(argv)
    );
    Ok(render_boot_defs(&initial_program))
}

fn render_boot_defs(initial_program: &str) -> String {
    format!(
        r#"// @generated by `xtask build`; do not edit.
pub(crate) enum InitialProgramSource {{
    RootfsEntry {{
        argv: Option<&'static [&'static str]>,
    }},
    EmbeddedApp {{
        bytes: &'static [u8],
        argv: Option<&'static [&'static str]>,
    }},
}}

pub(crate) const INITIAL_PROGRAM_SOURCE: InitialProgramSource =
    {initial_program};
"#
    )
}

fn render_argv(argv: Option<&[String]>) -> String {
    argv.map(|argv| {
        format!(
            "Some(&[{}])",
            argv.iter()
                .map(|argument| format!("{argument:?}"))
                .collect::<Vec<_>>()
                .join(", ")
        )
    })
    .unwrap_or_else(|| "None".to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_boot_defs_are_closed_and_track_embedded_bytes() {
        let rootfs = render_rootfs_entry_boot_defs(None);
        assert!(rootfs.contains("InitialProgramSource::RootfsEntry { argv: None }"));
        assert!(!rootfs.contains("include_bytes!"));

        let rootfs_argv = vec!["busybox".to_string(), "sh".to_string()];
        let rootfs = render_rootfs_entry_boot_defs(Some(&rootfs_argv));
        assert!(rootfs.contains("argv: Some(&[\"busybox\", \"sh\"])"));

        let argv = vec!["busybox".to_string(), "sh".to_string()];
        let embedded =
            render_embedded_app_boot_defs(Path::new("build/apps/init/init"), Some(&argv)).unwrap();
        assert!(embedded.contains("InitialProgramSource::EmbeddedApp"));
        assert!(embedded.contains("include_bytes!"));
        assert!(embedded.contains("build/apps/init/init"));
        assert!(embedded.contains("argv: Some(&[\"busybox\", \"sh\"])"));
    }

    #[test]
    fn generated_network_defs_are_closed_and_exact() {
        let absent = render_network_defs(None);
        assert!(absent.contains("STATIC_IPV4_DEPLOYMENT: Option<StaticIpv4Deployment> = None"));

        let ipv4 = StaticIpv4 {
            interface: "eth0".to_string(),
            address: "10.0.2.15".parse().unwrap(),
            prefix: 24,
            default_gateway: Some("10.0.2.2".parse().unwrap()),
        };
        let present = render_network_defs(Some(&ipv4));
        assert!(present.contains("interface: \"eth0\""));
        assert!(present.contains("address: [10, 0, 2, 15]"));
        assert!(present.contains("prefix: 24"));
        assert!(present.contains("default_gateway: Some([10, 0, 2, 2])"));
        assert!(!present.contains("Platform"));
        assert!(!present.contains("root"));
    }
}
